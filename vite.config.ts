import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

const OUT_DIR = 'dist';
const WORKER_NAME = 'sw.js';

/** Every file in the build output, as paths relative to it and separated by `/`. */
function listOutput(dir: string, root = dir): string[] {
  const files: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      files.push(...listOutput(full, root));
    } else {
      files.push(relative(root, full).split('\\').join('/'));
    }
  }
  return files.sort();
}

/**
 * Writes the service worker after the build.
 *
 * Generated rather than served from `public`: the bundle names are hashed, so a hand-written worker
 * would precache a list that no longer exists — which is exactly the stale-file failure this project
 * has already met once. Here the list and the cache name come from the real output.
 */
function offlinePlugin(): Plugin {
  return {
    name: 'tiltclimb-offline',
    apply: 'build',
    closeBundle() {
      const precache = listOutput(OUT_DIR).filter((file) => file !== WORKER_NAME);
      const fingerprint = createHash('sha256')
        .update(
          precache.map((file) => `${file}:${readFileSync(join(OUT_DIR, file)).length}`).join('|'),
        )
        .digest('hex')
        .slice(0, 12);

      const source = `// Generated by vite.config.ts — do not edit.
const CACHE = 'tiltclimb-${fingerprint}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await cache.addAll(PRECACHE.map((file) => new URL(file, self.registration.scope).href));
      // Take over at once instead of waiting for every tab to close: a waiting worker kept alive by
      // a client that never closes is how a stale build stays forever. Nothing reloads the page, so
      // a run in progress is not interrupted.
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key)));
      await self.clients.claim();
    })(),
  );
});

const isDocument = (request, url) =>
  request.mode === 'navigate' || url.pathname.endsWith('/') || url.pathname.endsWith('index.html');

async function networkFirst(request) {
  const cache = await caches.open(CACHE);
  try {
    const response = await fetch(request);
    if (response && response.ok) {
      await cache.put(request, response.clone());
    }
    return response;
  } catch (error) {
    const cached = await cache.match(request);
    if (cached) {
      return cached;
    }
    const fallback = await cache.match(new URL('index.html', self.registration.scope).href);
    if (fallback) {
      return fallback;
    }
    throw error;
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request);
  if (cached) {
    return cached;
  }
  const response = await fetch(request);
  if (response && response.ok) {
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') {
    return;
  }
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) {
    return;
  }
  // The worker must never be served from the cache, or an old copy keeps reinstalling itself and
  // the game never updates. Not calling respondWith lets the browser fetch it normally.
  if (url.pathname.endsWith('/${WORKER_NAME}')) {
    return;
  }
  event.respondWith(isDocument(request, url) ? networkFirst(request) : cacheFirst(request));
});
`;

      writeFileSync(join(OUT_DIR, WORKER_NAME), source);
      console.log(
        `offline: ${WORKER_NAME} with ${precache.length} files, cache tiltclimb-${fingerprint}`,
      );
    },
  };
}

// Dev server tuned for phone testing through a cloudflared quick tunnel:
// - allowedHosts: the tunnel hostname is random, so allow the whole domain
// - hmr over wss on 443: otherwise the HMR client reconnects to :5173 and dies
export default defineConfig({
  base: './',
  plugins: [offlinePlugin()],
  server: {
    host: '127.0.0.1',
    port: 5173,
    strictPort: true,
    allowedHosts: ['.trycloudflare.com', '.ngrok-free.app'],
    hmr: {
      protocol: 'wss',
      clientPort: 443,
    },
  },
  build: {
    target: 'es2022',
    sourcemap: true,
    // Excalibur alone is ~500 kB: one vendor bundle is expected, not a regression.
    chunkSizeWarningLimit: 700,
  },
});
